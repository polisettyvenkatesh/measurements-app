import { jsPDF } from 'jspdf';
import autoTable from 'jspdf-autotable';
import type { Sheet, SheetRow, Business } from './types';
import { calculateRow, formatNumber, roundDisplay } from './calc';

function hexToRgb(hex: string): [number, number, number] {
  const m = /^#?([0-9a-f]{6})$/i.exec(hex.trim());
  if (!m) return [30, 41, 59];
  const n = parseInt(m[1], 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}

export async function exportSheetPDF(sheet: Sheet, rows: SheetRow[], business: Business | null): Promise<void> {
  const precision = business?.decimal_precision ?? 2;
  const biz = business?.name ?? 'Measurement Sheet';
  const areaUnit = sheet.area_display_unit === 'sqm' ? 'm\u00b2' : 'sq ft';
  const isBlock = sheet.material_type === 'Block';
  const valueLabel = isBlock ? 'Volume (m\u00b3)' : `Area (${areaUnit})`;

  const accent = hexToRgb(business?.report_accent_color ?? '#1e293b');
  const tableTextColor = hexToRgb(business?.report_table_text_color ?? '#1e293b');
  const font = business?.report_font ?? 'helvetica';
  const showBorders = business?.report_show_borders ?? true;
  const reportTitle = business?.report_title || 'Measurement Sheet';

  const doc = new jsPDF({ unit: 'mm', format: 'a4' });
  const pageW = doc.internal.pageSize.getWidth();
  const pageH = doc.internal.pageSize.getHeight();
  const margin = 14;
  const contentW = pageW - margin * 2;

  const setFont = (style: 'normal' | 'bold' | 'italic' = 'normal') => doc.setFont(font, style);

  let logoData: { dataUrl: string; format: 'PNG' | 'JPEG' } | null = null;
  const logoUrl = business?.logo_url?.trim();
  if (logoUrl) {
    try {
      logoData = await loadImageAsDataUrl(logoUrl);
    } catch {
      logoData = null;
    }
  }

  const colCount = isBlock ? 5 : 4;
  const head = isBlock
    ? [['#', 'Length', 'Width', 'Height', valueLabel]]
    : [['#', 'Length', 'Width', valueLabel]];

  const calcForRow = (r: SheetRow) =>
    calculateRow(
      { length: r.length, width: r.width, height: r.height, quantity: r.quantity, unit: r.unit },
      sheet.material_type,
      sheet.area_display_unit,
    );

  const dim = (v: number) => formatNumber(v, precision);
  const displayRows = rows;

  const buildBodyChunk = (chunk: SheetRow[], startIndex: number) =>
    chunk.map((r, i) => {
      const calc = calcForRow(r);
      const val = calc.isValid ? formatNumber(calc.rowTotal, precision) : formatNumber(0, precision);
      const base = [String(startIndex + i + 1), dim(r.length), dim(r.width)];
      if (isBlock) base.push(dim(r.height));
      base.push(val);
      return base;
    });

  const showBusiness = sheet.show_business_name !== false;
  const drawHeader = () => {
    const logoSize = 12;
    if (showBusiness && logoData) {
      try {
        doc.addImage(logoData.dataUrl, logoData.format, margin, 3, logoSize, logoSize, undefined, 'FAST');
      } catch { /* ignore */ }
    }
    const textX = showBusiness && logoData ? margin + logoSize + 3 : margin;

    setFont('bold');
    doc.setFontSize(14);
    doc.setTextColor(accent[0], accent[1], accent[2]);
    if (showBusiness) {
      doc.text(biz, textX, 10);
    }
    doc.text(sheet.sheet_number, pageW - margin, 10, { align: 'right' });

    setFont('bold');
    doc.setFontSize(12);
    doc.setTextColor(accent[0], accent[1], accent[2]);
    doc.text(reportTitle, pageW / 2, 16, { align: 'center' });

    setFont('normal');
    doc.setFontSize(9.5);
    doc.setTextColor(100, 116, 139);
    const infoLine = `Customer: ${sheet.customer_name}  |  Product: ${sheet.project_name || '\u2014'}`;
    doc.text(infoLine, margin, 21);
    doc.text(formatDisplayDate(sheet.date), pageW - margin, 21, { align: 'right' });

    doc.setDrawColor(accent[0], accent[1], accent[2]);
    doc.setLineWidth(0.4);
    doc.line(margin, 23, pageW - margin, 23);
  };

  const drawFooter = (pageNum: number) => {
    setFont('normal');
    doc.setFontSize(8);
    doc.setTextColor(148, 163, 184);
    doc.text(
      `Generated by Granite & Block Measurement Sheets  \u00b7  Page ${pageNum}`,
      pageW / 2,
      pageH - 6,
      { align: 'center' },
    );
  };

  const ROWS_PER_COL = 40;
  const headerBottom = 25;
  const useMultiColumn = displayRows.length > ROWS_PER_COL;
  let afterTablesY = headerBottom;

  const tableBaseStyles = (fontSize: number) => ({
    font,
    fontSize,
    cellPadding: fontSize < 8 ? 0.8 : Math.max(1.5, fontSize * 0.15),
    textColor: tableTextColor,
    lineColor: showBorders ? [226, 232, 240] as [number, number, number] : [255, 255, 255] as [number, number, number],
    lineWidth: showBorders ? 0.1 : 0,
    halign: 'center' as const,
  });

  const headStyles = (fontSize: number) => ({
    fillColor: accent,
    textColor: [255, 255, 255] as [number, number, number],
    fontSize,
    fontStyle: 'bold' as const,
    halign: 'center' as const,
    lineColor: showBorders ? accent : [255, 255, 255] as [number, number, number],
    lineWidth: showBorders ? 0.1 : 0,
  });

  if (displayRows.length === 0) {
    drawHeader();
    const emptyBody = [[{
      content: 'No measurement rows.',
      colSpan: colCount,
      styles: { halign: 'center' as const, textColor: [148, 163, 184] as [number, number, number] },
    }]] as unknown as string[][];

    autoTable(doc, {
      head,
      body: emptyBody,
      startY: headerBottom,
      margin: { left: margin, right: margin, top: headerBottom, bottom: 24 },
      styles: tableBaseStyles(8.5),
      headStyles: headStyles(8.5),
    });
    // @ts-expect-error autoTable augments doc with lastAutoTable
    afterTablesY = doc.lastAutoTable.finalY + 6;

  } else if (!useMultiColumn) {
    const reserveH = 36;
    const availableH = pageH - headerBottom - reserveH;
    const fixedRowCount = ROWS_PER_COL;
    const headerRowH = 8;
    const cellPad = 0.8;
    const solveFS = (availableH - headerRowH) / (fixedRowCount * 0.5) - (2 * cellPad) / 0.5;
    const singleFontSize = Math.round(Math.min(10, Math.max(6, solveFS)) * 10) / 10;
    const singleCellPad = Math.max(0.8, singleFontSize * 0.12);
    const footerReserve = 10;

    drawHeader();
    autoTable(doc, {
      head,
      body: buildBodyChunk(displayRows, 0),
      startY: headerBottom,
      margin: { left: margin, right: margin, top: headerBottom, bottom: footerReserve },
      styles: { ...tableBaseStyles(singleFontSize), cellPadding: singleCellPad },
      headStyles: headStyles(singleFontSize),
      columnStyles: {
        0: { halign: 'center', cellWidth: 14 },
        1: { halign: 'center' },
        2: { halign: 'center' },
        ...(isBlock ? { 3: { halign: 'center' }, 4: { halign: 'center' } } : { 3: { halign: 'center' } }),
      },
      alternateRowStyles: { fillColor: [248, 250, 252] },
      rowPageBreak: 'avoid',
    });
    // @ts-expect-error autoTable augments doc with lastAutoTable
    const tableFinalY = doc.lastAutoTable.finalY;

    const colQty = displayRows.reduce((s, r) => s + (r.quantity ?? 0), 0);
    const colArea = displayRows.reduce((s, r) => {
      const cr = calcForRow(r);
      return s + (cr.isValid ? roundDisplay(cr.rowTotal, 4) : 0);
    }, 0);
    setFont('bold');
    doc.setFontSize(singleFontSize);
    doc.setTextColor(accent[0], accent[1], accent[2]);
    doc.setDrawColor(accent[0], accent[1], accent[2]);
    doc.setLineWidth(0.2);
    const divY = tableFinalY + 7;
    doc.line(margin, divY, pageW - margin, divY);
    const totalTextY = divY + 5;
    doc.text(`Qty: ${formatNumber(colQty, 0)}`, margin, totalTextY);
    const colValLabel = isBlock ? 'Vol' : 'Area';
    doc.text(`${colValLabel}: ${formatNumber(roundDisplay(colArea, precision), precision)}`, pageW - margin, totalTextY, { align: 'right' });

    afterTablesY = totalTextY + 4;

  } else {
    const COLS_PER_PAGE = 3;
    const ROWS_PER_PAGE = ROWS_PER_COL * COLS_PER_PAGE;
    const totalPages = Math.ceil(displayRows.length / ROWS_PER_PAGE);
    const colGap = 4;
    const colW = (contentW - 2 * colGap) / 3;

    const subWidths = isBlock ? [7, 12, 12, 12, 13] : [8, 15, 15, 18];
    const colColumnStyles: Record<number, { halign: 'center'; cellWidth: number }> = {};
    for (let i = 0; i < subWidths.length; i++) {
      colColumnStyles[i] = { halign: 'center', cellWidth: subWidths[i] };
    }

    const colReserveH = 36;
    const colAvailableH = pageH - headerBottom - colReserveH;
    const colHeaderRowH = 8;
    const colCellPad = 0.8;
    const colSolveFS = (colAvailableH - colHeaderRowH) / (ROWS_PER_COL * 0.5) - (2 * colCellPad) / 0.5;
    const colFontSize = Math.round(Math.min(10, Math.max(6, colSolveFS)) * 10) / 10;
    const colCellPadFinal = Math.max(0.8, colFontSize * 0.12);

    for (let p = 0; p < totalPages; p++) {
      if (p > 0) doc.addPage();
      drawHeader();

      let maxFinalY = headerBottom;

      for (let c = 0; c < COLS_PER_PAGE; c++) {
        const startIdx = p * ROWS_PER_PAGE + c * ROWS_PER_COL;
        const chunk = displayRows.slice(startIdx, startIdx + ROWS_PER_COL);
        if (chunk.length === 0) continue;

        const colLeft = margin + c * (colW + colGap);
        const colRight = pageW - colLeft - colW;

        autoTable(doc, {
          head,
          body: buildBodyChunk(chunk, startIdx),
          startY: headerBottom,
          margin: { left: colLeft, right: colRight, top: headerBottom, bottom: 10 },
          styles: { ...tableBaseStyles(colFontSize), cellPadding: colCellPadFinal },
          headStyles: headStyles(colFontSize),
          columnStyles: colColumnStyles,
          alternateRowStyles: { fillColor: [248, 250, 252] },
          rowPageBreak: 'avoid',
        });

        // @ts-expect-error autoTable augments doc with lastAutoTable
        const fy = doc.lastAutoTable.finalY;
        maxFinalY = Math.max(maxFinalY, fy);

        let cty = fy + 7;
        const colQty = chunk.reduce((s, r) => s + (r.quantity ?? 0), 0);
        const colArea = chunk.reduce((s, r) => {
          const cr = calcForRow(r);
          return s + (cr.isValid ? roundDisplay(cr.rowTotal, 4) : 0);
        }, 0);
        setFont('bold');
        doc.setFontSize(colFontSize);
        doc.setTextColor(accent[0], accent[1], accent[2]);
        doc.setDrawColor(accent[0], accent[1], accent[2]);
        doc.setLineWidth(0.2);
        doc.line(colLeft, cty, colLeft + colW, cty);
        cty += 5;
        doc.text(`Qty: ${formatNumber(colQty, 0)}`, colLeft, cty);
        const colValLabel = isBlock ? 'Vol' : 'Area';
        doc.text(`${colValLabel}: ${formatNumber(roundDisplay(colArea, precision), precision)}`, colLeft + colW, cty, { align: 'right' });
        cty += 4;
        maxFinalY = Math.max(maxFinalY, cty);
      }

      afterTablesY = maxFinalY + 2;
    }
  }

  let y = afterTablesY + 4;
  if (y > pageH - 20) {
    doc.addPage();
    drawHeader();
    y = headerBottom + 4;
  }
  const totalArea = formatNumber(roundDisplay(sheet.total_area_sqft, precision), precision);
  const totalLabel = isBlock ? 'Grand Total Volume' : 'Grand Total Area';
  const totalsW = 90;
  const totalsX = pageW - margin - totalsW;
  doc.setFontSize(10);
  setFont('normal');
  doc.setTextColor(30, 41, 59);
  doc.text('Total Quantity', totalsX, y);
  doc.text(formatNumber(sheet.total_quantity, 0), pageW - margin, y, { align: 'right' });
  y += 5;
  doc.setDrawColor(accent[0], accent[1], accent[2]);
  doc.setLineWidth(0.4);
  doc.line(totalsX, y - 2, pageW - margin, y - 2);
  setFont('bold');
  doc.setFontSize(11);
  doc.text(totalLabel, totalsX, y + 3);
  doc.text(`${totalArea} ${areaUnit}`, pageW - margin, y + 3, { align: 'right' });
  y += 8;

  const totalDocPages = doc.getNumberOfPages();
  for (let i = 1; i <= totalDocPages; i++) {
    doc.setPage(i);
    drawFooter(i);
  }

  const filename = `${sheet.sheet_number}_${sheet.customer_name.replace(/[^a-z0-9]+/gi, '_')}.pdf`;
  doc.save(filename);
}

function formatDisplayDate(iso: string): string {
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return iso;
  return d.toLocaleDateString(undefined, { year: 'numeric', month: 'short', day: 'numeric' });
}

function loadImageAsDataUrl(url: string): Promise<{ dataUrl: string; format: 'PNG' | 'JPEG' }> {
  return new Promise((resolve, reject) => {
    if (url.startsWith('data:image/')) {
      const fmt = url.startsWith('data:image/png') ? 'PNG' : 'JPEG';
      resolve({ dataUrl: url, format: fmt });
      return;
    }

    const img = new Image();
    img.crossOrigin = 'anonymous';
    img.onload = () => {
      try {
        const canvas = document.createElement('canvas');
        canvas.width = img.naturalWidth;
        canvas.height = img.naturalHeight;
        const ctx = canvas.getContext('2d');
        if (!ctx) {
          reject(new Error('Canvas not supported'));
          return;
        }
        ctx.drawImage(img, 0, 0);
        const dataUrl = canvas.toDataURL('image/png');
        resolve({ dataUrl, format: 'PNG' });
      } catch (e) {
        reject(e instanceof Error ? e : new Error('Image conversion failed'));
      }
    };
    img.onerror = () => reject(new Error('Logo image failed to load'));
    img.src = url;
  });
}